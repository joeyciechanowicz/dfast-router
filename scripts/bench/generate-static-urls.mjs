import { createWriteStream } from "node:fs";
import { once } from "node:events";
import { relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { findRoutesFile, siblingUrlsFile, takeFlag, takeNumberFlag } from "../../bench/flags.mjs";

function createRng(initial) {
  let value = initial >>> 0;
  return () => {
    value |= 0;
    value = (value + 0x6d2b79f5) | 0;
    let t = Math.imul(value ^ (value >>> 15), 1 | value);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function normalizePath(path) {
  if (!path) return "/";
  if (path.charCodeAt(0) === 47) return path;
  return `/${path}`;
}

const routesFile = findRoutesFile(takeFlag("--routes") ?? "generic");
const routesModulePath = relative(process.cwd(), routesFile);
const target = takeNumberFlag("--target", 3_000_000);
const seed = takeNumberFlag("--seed", 0x5a17f00d);
const outFlag = takeFlag("--out");
const outPath = outFlag ? resolve(process.cwd(), outFlag) : siblingUrlsFile(routesFile);

const routesModule = await import(pathToFileURL(routesFile).href);
if (!Array.isArray(routesModule.routes)) {
  throw new Error(
    `Routes module "${routesModulePath}" must export a routes array.`,
  );
}
const routes = routesModule.routes;

const weightedRoutes = [];
let totalWeight = 0;
for (const route of routes) {
  if (!route || typeof route.generateUrl !== "function") continue;
  const weight = Number(route.count) > 0 ? Number(route.count) : 1;
  totalWeight += weight;
  weightedRoutes.push({ generateUrl: route.generateUrl, cumulative: totalWeight });
}
if (!weightedRoutes.length) {
  throw new Error(`No routes with generateUrl found in "${routesModulePath}".`);
}

function pickRoute(rng) {
  const roll = rng() * totalWeight;
  for (const route of weightedRoutes) {
    if (roll < route.cumulative) return route;
  }
  return weightedRoutes[weightedRoutes.length - 1];
}

const rng = createRng(seed);
const stream = createWriteStream(outPath, { encoding: "utf8" });
stream.write("// Generated by scripts/bench/generate-static-urls.mjs\n");
stream.write(`// routesModule=${routesModulePath}\n`);
stream.write(`// target=${target} seed=${seed}\n`);
stream.write("export const precomputedUrls = [\n");
for (let i = 0; i < target; i += 1) {
  const route = pickRoute(rng);
  const url = normalizePath(route.generateUrl(rng));
  if (!stream.write(`  ${JSON.stringify(url)},\n`)) {
    await once(stream, "drain");
  }
}
stream.write("];\n");
stream.end();
await once(stream, "finish");
console.log(`Wrote ${target} urls to ${outPath}`);
